from vernadsky_lab import register_mineral, record, summary, mineral_report, to_csv

print("=== Лабораторія Вернадського ===\n")

print("Реєстрація мінералів:")
print(register_mineral("Берил", "Be₃Al₂Si₆O₁₈", 8, "США", 1900))
